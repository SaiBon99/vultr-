// Fluid type: reads the min/max size tokens and writes clamp() values for each step. Run through tokens:build.
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync('tokens/primitive/type.tokens.json', 'utf8')).primitive.type;
const num = (k) => tokens[k].$value.value;
const vpMin = num('viewport-min');
const vpMax = num('viewport-max');
const steps = Object.keys(tokens).filter((k) => k.startsWith('size-') && k.endsWith('-min')).map((k) => k.slice(5, -4));
const f = (n) => Number(n.toFixed(4));
const lines = steps.map((s) => {
  const lo = num(`size-${s}-min`);
  const hi = num(`size-${s}-max`);
  const slope = (hi - lo) / (vpMax - vpMin);
  const value = lo === hi ? `${f(lo)}rem` : `clamp(${f(lo)}rem, ${f(lo - slope * vpMin)}rem + ${f(slope * 100)}vw, ${f(hi)}rem)`;
  return `  --text-${s}: ${value};`;
});
const body = lines.join('\n');
const css = true ? `@theme {\n${body}\n}\n` : `:root {\n${body}\n}\n`;
writeFileSync('src/styles/fluid.css', '/* Generated by tokens/tools/fluid.mjs from tokens/primitive/type.tokens.json. Do not edit. */\n' + css);
console.log(`tokens: wrote src/styles/fluid.css (${steps.length} sizes)`);
